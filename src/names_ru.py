def gen_name(ru: str) -> str:
    """Родительный падеж русского имени."""
    if ru in GEN_OVERRIDE:
        return GEN_OVERRIDE[ru]
    if ru.endswith("ий"):
        return ru[:-2] + "ия"
    if ru.endswith("а"):
        return ru[:-1] + "ы"
    if ru.endswith("я"):
        return ru[:-1] + "и"
    if ru.endswith("ь"):
        return ru[:-1] + "и"
    if ru.endswith("й"):
        return ru[:-1] + "я"
    return ru + "а"
