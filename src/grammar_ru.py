def noun_gender(word: str) -> str:
    w = word.strip().lower()
    if w in GENDER:
        return GENDER[w]
    if w in GENDER_OVERRIDE:
        return GENDER_OVERRIDE[w]
    if w.endswith(("ья", "ья")):
        return "pl"
    if w.endswith(("и", "ы")) and w not in ("штаны",):
        return "pl"
    if w.endswith(("а", "я")):
        return "f"
    if w.endswith(("о", "е", "ё")):
        return "n"
    return "m"


