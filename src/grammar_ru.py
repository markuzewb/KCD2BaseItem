def _is_adj(word: str) -> bool:
    w = word.lower()
    if w in ADJ_KEYS:
        return True
    return w.endswith(("ый", "ий", "ой", "ая", "яя", "ое", "ее", "ые", "ие")) and len(w) > 4


def agree(adj: str, gender: str) -> str:
    """Привести прилагательное к нужному роду/числу (именительный падеж)."""
    a = adj
    if not a:
        return a
    kind = "hard"
    stem = a
    if a.endswith("ой"):
        kind, stem = "stress", a[:-2]
    elif a.endswith("ый"):
        kind, stem = "hard", a[:-2]
    elif a.endswith("ий"):
        stem = a[:-2]
        if stem.endswith(("к", "г", "х", "ск")):
            kind = "sib"
        elif stem.endswith(("ж", "ш", "ч", "щ")):
            # «нищий» -> «нищая», «свежий» -> «свежая» (без «ь» в женском)
            kind = "sib"
        elif stem.endswith(("н", "т", "р", "л", "с", "з", "д", "в", "м", "п", "б", "ф")):
            kind = "soft"
    elif a.endswith("ая"):
        kind, stem = "hard", a[:-2]
    elif a.endswith("яя"):
        kind, stem = "soft", a[:-2]
    elif a.endswith("ое"):
        kind, stem = "hard", a[:-2]
    elif a.endswith("ее"):
        kind, stem = "soft", a[:-2]
    elif a.endswith("ые"):
        # «мёртвые» уже во мн. числе — в ед. числе восстанавливаем основу
        stem = a[:-2]
        if stem.endswith(("ов", "ев", "н", "т", "р", "л", "с", "з", "д", "м", "п", "б", "ф", "в")):
            kind = "hard"
        elif stem.endswith(("ж", "ш", "ч", "щ")):
            kind = "sib"
        else:
            kind = "hard"
    elif a.endswith("ие"):
        stem = a[:-2]
        if stem.endswith(("ск",)):
            kind = "sib"
        elif stem.endswith(("ж", "ш", "ч", "щ")):
            kind = "sib"
        else:
            kind = "soft"
    table = {
        "hard":   {"m": "ый", "f": "ая", "n": "ое", "pl": "ые"},
        "soft":   {"m": "ий", "f": "яя", "n": "ее", "pl": "ие"},
        "sib":    {"m": "ий", "f": "ая", "n": "ое", "pl": "ие"},
        "stress": {"m": "ой", "f": "ая", "n": "ое", "pl": "ые"},
    }
    return stem + table[kind][gender]


