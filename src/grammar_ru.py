def genitive(noun: str) -> str:
    """Родительный падеж для существительного-определения (упрощённо)."""
    w = noun.strip().lower()
    if w in GEN_PL:
        return GEN_PL[w]
    g = noun_gender(w)
    if g == "pl":
        return noun
    if g == "f":
        if w.endswith("а"):
            return noun[:-1] + "ы"
        if w.endswith("я"):
            return noun[:-1] + "и"
        if w.endswith("ь"):
            return noun[:-1] + "и"
        return noun
    if g == "n":
        if w.endswith("о"):
            return noun[:-1] + "а"
        if w.endswith("е"):
            return noun[:-1] + "я"
        return noun
    if w.endswith("ь"):
        return noun[:-1] + "я"
    if w.endswith("й"):
        return noun[:-1] + "я"
    if w.endswith(("а", "я")):
        return noun[:-1] + ("и" if w.endswith("я") else "ы")
    return noun + "а"


DROP_EN = {"a", "an", "the", "of", "from", "for", "to", "on", "in",
           "by", "about", "o'", "á", "at", "with_"}


def _clean(word: str) -> str:
    return word.strip(" ,;:()[]\"")


def _word_ru(tok: str):
    """Перевести одиночное слово. Возвращает (en_lower, ru, kind).

    Приоритет: точное SPECIAL -> существительное NOUNS -> атрибутивная
    форма ATTR (используется только перед существительным).
    """
    tl = _clean(tok).lower()
    if tl in SPECIAL:
        return tl, SPECIAL[tl], "special"
    if tl in NOUNS:
        ru = NOUNS[tl]
        # «колыбельная», «сталь» пишутся как прилагательные, но это существительные
        if ru in GENDER_OVERRIDE or ru in GENDER:
            return tl, ru, "noun"
        return tl, ru, ("adj" if _is_adj(ru) else "noun")
    if tl in ATTR:
        return tl, ATTR[tl], "attr"
    # «courtiers» -> «courtier», «guards» -> «guard»
    if tl.endswith("s") and not tl.endswith(("ss", "'s")):
        sing = tl[:-1]
        if sing in SPECIAL:
            return tl, SPECIAL[sing], "special"
        if sing in NOUNS:
            ru = NOUNS[sing]
            if ru in GENDER_OVERRIDE or ru in GENDER:
                return tl, ru, "noun"
            return tl, ru, ("adj" if _is_adj(ru) else "noun")
        if sing in ATTR:
            return tl, ATTR[sing], "attr"
    return tl, _clean(tok), "unknown"


def _agree_attr(form: str, gender: str) -> str:
    """Согласовать определение с головным словом (именительный падеж)."""
    if not form:
        return form
    if form.endswith(("ье", "ье")):
        stem = form[:-2]
        return {"m": stem + "ий", "f": stem + "ья", "n": stem + "ье", "pl": stem + "ьи"}[gender]
    if _is_adj(form):
        return agree(form, gender)
    if form.endswith(("ова", "ева", "ина", "ына")):
        # притяжательное: «папина» -> «папин»
        return form[:-1]
    return form


def _phrase_to_ru(tokens, gender_hint=None):
    """Перевести фразу «определения + существительное»."""
    pairs = [_word_ru(t) for t in tokens]
    pairs = [p for p in pairs if p[1]]
    if not pairs:
        return None, None

    # головное существительное: последнее, что не прилагательное
    noun_idx = None
    for j in range(len(pairs) - 1, -1, -1):
        if pairs[j][2] == "noun" and not _is_adj(pairs[j][1]):
            noun_idx = j
            break
    if noun_idx is None:
        for j in range(len(pairs) - 1, -1, -1):
            if pairs[j][2] == "noun":
                noun_idx = j
                break
    if noun_idx is None:
        for j in range(len(pairs) - 1, -1, -1):
            if pairs[j][1] in GENDER:
                noun_idx = j
                break
    if noun_idx is None:
        return " ".join(p[1] for p in pairs), None

    noun = pairs[noun_idx][1]
    g = gender_hint or noun_gender(noun)
    # если головное слово всё-таки прилагательное («сталь» размечено как adj),
    # род берём у последнего настоящего существительного
    if _is_adj(noun):
        for en, ru, kind in reversed(pairs[:noun_idx]):
            if kind in ("noun", "special") and not _is_adj(ru):
                g = noun_gender(ru)
                break

    pre = []
    for en, ru, kind in pairs[:noun_idx]:
        # 1) относительное прилагательное из ATTR (не для головного слова)
        if kind == "attr" or (en in ATTR and not _is_adj(ru) and _is_adj(ATTR[en])):
            a = ATTR.get(en, ru)
            pre.append(("adj", a))
        elif kind == "adj":
            pre.append(("adj", ru))
        elif kind == "noun":
            # «Toledo steel» — это не «сталь Толедо», а «толедская сталь»:
            # если есть относительное прилагательное, оно точнее родительного
            alt = ATTR.get(en)
            if alt and _is_adj(alt):
                pre.append(("adj", alt))
            else:
                pre.append(("gen", genitive(ru)))
        else:
            pre.append(("raw", ru))

    adjs = [val for kind, val in pre if kind == "adj"]
    gens = [val for kind, val in pre if kind == "gen"]
    raws = [val for kind, val in pre if kind == "raw"]

    out = []
    for val in adjs:
        out.append(_agree_attr(val, g) if val.endswith("ье") else agree(val, g))
    out.extend(raws)
    out.append(noun)
    out.extend(gens)          # родительный — после головного слова
    out.extend(p[1] for p in pairs[noun_idx + 1:])
    return " ".join(x for x in out if x), g


def _gen_word(w: str) -> str:
    """Родительный падеж существительного (упрощённо)."""
    low = w.lower()
    if any(ch.isdigit() for ch in w):
        return w
    # заимствованные имена на -о/-и/-у не склоняются: Гуго, Батти, Дитто
    if low.endswith(("го", "ти", "то", "ни", "ли", "си", "ди", "у")) and len(low) > 3:
        return w
    if low in GEN_PL:
        return GEN_PL[low]
    if noun_gender(w) == "pl":
        if low.endswith(("тки", "дки")):
            return w[:-3] + "ток"
        if low.endswith(("ки", "ги", "хи")):
            return w[:-2] + "ок"
        if low.endswith(("чи", "жи", "ши", "щи")):
            return w[:-1] + "ей"
        if low.endswith("и"):
            return w[:-1] + "ей"
        if low.endswith("цы"):
            return w[:-2] + "ец"
        if low.endswith("ы"):
            return w[:-2]
        return w + "ов"
    if low.endswith("ия"):
        return w[:-1] + "и"
    if low.endswith(("а",)):
        return w[:-1] + "ы"
    if low.endswith(("я",)):
        return w[:-1] + "и"
    if low.endswith("ь"):
        # «король» -> «короля», «палач» не сюда; «дверь» -> «двери»
        if low.endswith(("ель", "оль", "аль", "уль", "ыль", "арь", "ырь", "ень", "онь")):
            return w[:-1] + "я"
        return w[:-1] + "и"
    if low.endswith("о"):
        return w[:-1] + "а"
    if low.endswith("е"):
        return w[:-1] + "я"
    if low.endswith("ий"):
        return w[:-2] + "ия"
    if low.endswith("й"):
        return w[:-1] + "я"
    return w + "а"


def _genitive_phrase(tokens):
    """Перевести фразу в родительный падеж (для «of X», «from X», притяжательных)."""
    tokens = [t for t in tokens if t and t.lower() not in DROP_EN]
    if not tokens:
        return None
    key = " ".join(t.lower() for t in tokens).strip()
    if key in NAMES:
        return gen_name(NAMES[key])
    if len(tokens) == 1:
        k = tokens[0].lower().strip(".,!?")
        if k in NAMES:
            return gen_name(NAMES[k])
    # «Bishop Thomas» / «Lord Capon» — титул + имя
    if len(tokens) == 2:
        t0 = tokens[0].lower().strip(".,!?")
        t1 = tokens[1].lower().strip(".,!?")
        if t1 in NAMES and t0 in NAMES:
            title = NAMES[t0]
            title = title if title in ("Святой", "Пан") else title.lower()
            return f"{title} {gen_name(NAMES[t1])}"

    # фраза содержит имена собственные -> переводим каждое слово через NAMES
    name_words = []
    allnames = True
    for t in tokens:
        k = t.lower().strip(".,!?")
        if k in NAMES:
            name_words.append(NAMES[k])
        elif k in NOUNS:
            name_words.append(NOUNS[k])
            allnames = False
        else:
            allnames = False
            break
    if allnames and name_words:
        return " ".join(name_words)

    ru, g = _phrase_to_ru(tokens)
    if not ru:
        return None
    # если фраза целиком — имя собственное в словаре
    if ru.lower() in {v.lower() for v in NAMES.values()}:
        return gen_name(ru)
    words = ru.split()
    if not words:
        return None
    # головное слово — последнее, ставим его в родительный падеж
    head = words[-1]
    # имя собственное внутри фразы
    if head in NAMES.values():
        words[-1] = gen_name(head)
    elif head.lower() in ("меч", "щит", "топор", "шлем", "перстень", "книга", "карта", "ключ", "корабль"):
        words[-1] = _gen_word(head)
    else:
        words[-1] = _gen_word(head)
    # согласуем определения перед головой в родительном падеже
    for k in range(len(words) - 1):
        w = words[k]
        if _is_adj(w):
            if w.endswith(("ые", "ие")):
                words[k] = w[:-2] + "ых"
            elif w.endswith(("ый", "ий", "ой")):
                words[k] = w[:-2] + "ого"
            elif w.endswith(("ая", "яя")):
                words[k] = w[:-2] + "ой"
            elif w.endswith(("ое", "ее")):
                words[k] = w[:-2] + "ого"
    return " ".join(words)


NUM_RE = re.compile(r"(?:^|\s)([IVX]{1,5}|\d+)(?=$|\s|[.,!?])")


def _split_clauses(text):
    """Разбить название на клаузы по служебным словам, сохранив их тип."""
    pattern = re.compile(r"\s*\b(of|from|with|and)\b\s*", re.I)
    parts = pattern.split(text)
    clauses = []
    kind = "head"
    for chunk in parts:
        if chunk is None:
            continue
        c = chunk.strip()
        if c.lower() in ("of", "from", "with", "and"):
            kind = c.lower()
            continue
        if not c:
            continue
        clauses.append((kind, c))
        kind = "of"
    return clauses


def translate_name(name: str, gender_hint: str | None = None) -> str:
    """Перевести английское название предмета в русское."""
    if not name:
        return ""
    raw = name.strip().replace("\u2019", "'")
    raw = re.sub(r"<[^>]+>", "", raw).strip()
    raw = raw.rstrip(".")
    low = raw.lower()

    if low in SPECIAL:
        return SPECIAL[low]
    if re.sub(r"^(a|an|the)\s+", "", low) in SPECIAL:
        return SPECIAL[re.sub(r"^(a|an|the)\s+", "", low)]

    # отделяем хвостовой номер части (I, II, III, ...)
    numerals = []
    while True:
        m = re.search(r"\s+([IVX]{1,5}|\d+)$", raw)
        if not m:
            break
        numerals.insert(0, m.group(1))
        raw = raw[: m.start()].strip()

    # составные названия
    if low.strip() in COMPOUND:
        return COMPOUND[low.strip()]
    # повторная проверка словаря после снятия номера
    low2 = raw.lower()
    if low2 in SPECIAL:
        return (SPECIAL[low2] + (" " + " ".join(numerals) if numerals else "")).strip()
    if re.sub(r"^(a|an|the)\s+", "", low2) in SPECIAL:
        return (SPECIAL[re.sub(r"^(a|an|the)\s+", "", low2)] +
                (" " + " ".join(numerals) if numerals else "")).strip()
    # «!» и прочие знаки в словарных ключах
    if low2 in COMPOUND:
        return (COMPOUND[low2] + (" " + " ".join(numerals) if numerals else "")).strip()
    if low2.replace("!", "").strip() in SPECIAL:
        return (SPECIAL[low2.replace("!", "").strip()] +
                (" " + " ".join(numerals) if numerals else "")).strip()

    # «St. X» / «St X» -> «св. X»
    raw = re.sub(r"\bSt\.?\s+", "св. ", raw)

    # титул + имя + предмет: «Lord Pisek heater shield» -> «щит-утюг пана Писека»
    mt = re.match(r"^(Lord|Lady|Sir|King|Queen|Bishop|Master)\s+([A-Za-zÀ-ž]+)\s+(.+)$", raw)
    if mt:
        title, nm, rest = mt.group(1).lower(), mt.group(2).lower(), mt.group(3)
        if nm in NAMES:
            ru_head, _g = _phrase_to_ru([t for t in rest.split() if t.lower() not in DROP_EN])
            if ru_head:
                ttl = NAMES.get(title, title.capitalize())
                ttl = ttl if ttl in ("Святой", "Пан") else ttl.lower()
                txt = f"{ru_head} {ttl} {gen_name(NAMES[nm])}".strip()
                return (txt + (" " + " ".join(numerals) if numerals else "")).strip()

    # притяжательные -> список владельцев
    owners = []

    def _poss(mt):
        w = mt.group(1)
        _en, ru, kind = _word_ru(w)
        # «Courtier's coat» — не владелец, а относительное прилагательное
        if kind == "attr" or _is_adj(ru):
            return w
        owners.append(w)
        return "\x00"

    work = re.sub(r"([A-Za-zÀ-ž'\u2019\-]+)['\u2019]s\b", _poss, raw)
    work = work.replace("\x00", " ").strip()


    clauses = _split_clauses(work)
    if not clauses:
        return ""

    out = []
    head_done = False
    for kind, chunk in clauses:
        toks = [t for t in chunk.split() if t and t.lower() not in DROP_EN]
        if not toks:
            continue
        if kind == "head" and not head_done:
            main, _g = _phrase_to_ru(toks, gender_hint)
            if main:
                out.append(main)
            head_done = True
        elif kind == "with" or kind == "and":
            for tok in toks:
                tl = _clean(tok).lower()
                if tl in POST:
                    out.append(POST[tl])
                else:
                    ru, _ = _phrase_to_ru([tok])
                    out.append(POST.get(tl, ru or ""))
        elif kind == "from":
            gen = _genitive_phrase(toks)
            if gen:
                out.insert(1 if out else 0, "из " + gen)
        else:  # of
            gen = _genitive_phrase(toks)
            if gen:
                out.append(gen)

    for ow in owners:
        gen = _genitive_phrase(ow.split())
        if gen:
            out.append(gen)

    out = [x for x in out if x and x.strip()]
    out.extend(numerals)
    text = " ".join(out)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def capitalize(name: str) -> str:
    if not name:
        return name
    return name[0].upper() + name[1:]
